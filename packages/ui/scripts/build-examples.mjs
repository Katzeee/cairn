import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Each example file is rendered as-is and shown as-is, so the code beside a preview is the preview.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const examplesRoot = join(root, "src/catalog/examples");
const output = join(root, "src/catalog/generated/examples.ts");

async function files(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map((entry) => (entry.isDirectory() ? files(join(directory, entry.name)) : [join(directory, entry.name)])),
  );
  return nested.flat().filter((path) => path.endsWith(".tsx"));
}

const examples = [];
for (const path of (await files(examplesRoot)).sort()) {
  const id = relative(examplesRoot, path).replaceAll("\\", "/").replace(/\.tsx$/, "");
  const source = (await readFile(path, "utf8")).replaceAll("\r\n", "\n").trim();
  if (!/^export default function \w+/m.test(source)) throw new Error(`Example ${id} must export a default function`);
  examples.push({ id, source });
}

const module =
  "// Generated by scripts/build-examples.mjs from src/catalog/examples.\n" +
  'import type { ComponentType } from "react";\n\n' +
  examples.map(({ id }, index) => `import Example${index} from "../examples/${id}.js";\n`).join("") +
  "\nexport const examples: Readonly<Record<string, Readonly<{ Component: ComponentType; source: string }>>> = {\n" +
  examples.map(({ id, source }, index) => `  ${JSON.stringify(id)}: { Component: Example${index}, source: ${JSON.stringify(source)} },\n`).join("") +
  "};\n";

await mkdir(dirname(output), { recursive: true });
if ((await readFile(output, "utf8").catch(() => "")) !== module) await writeFile(output, module);
